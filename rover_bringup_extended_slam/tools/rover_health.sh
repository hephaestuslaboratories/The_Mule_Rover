#!/usr/bin/env bash
# rover_health.sh — Jetson-side health recorder.
#
#   RUN THIS ON THE JETSON HOST, NOT INSIDE THE CONTAINER.
#   tegrastats and the kernel ring buffer do not exist in the container.
#
#   bash rover_health.sh [output_dir]
#   (Ctrl-C to stop.  Leave it running for the whole session.)
#
# Answers the questions ROS cannot:
#   * did the JETSON reboot?          boot_id changes on every boot — definitive
#   * was it a POWER-ON reset or a
#     clean/software reboot?          boot record + kernel reason at startup
#   * was there a brownout?           VDD_IN sag in tegrastats right before a gap
#   * did the ESP32 or LiDAR drop
#     off USB?                        cdc_acm / ch341 / usb disconnect in dmesg
#   * thermal throttle?               tegrastats thermal + throttle fields
#
# What it CANNOT tell you: whether the Jetson stalled without rebooting.  The
# only evidence for that is the ESP32's WATCHDOG_TRIGGERED line, which the
# bridge now republishes on /rover/link_status.

set -u

OUT="${1:-$HOME/rover_health}"
STAMP="$(date +%Y%m%d_%H%M%S)"
DIR="$OUT/$STAMP"
mkdir -p "$DIR"

echo "=== rover_health -> $DIR ==="
echo "    leave running for the whole session; Ctrl-C to stop"

# ── Boot identity: the definitive reboot marker ──────────────────────────────
# boot_id is regenerated by the kernel on every boot.  Compare it between
# sessions: same id = no reboot, different id = the Jetson restarted.
{
  echo "session_start: $(date -Is)"
  echo "boot_id:       $(cat /proc/sys/kernel/random/boot_id 2>/dev/null)"
  echo "uptime_s:      $(cut -d' ' -f1 /proc/uptime 2>/dev/null)"
  echo "uptime_human:  $(uptime -p 2>/dev/null)"
  echo "booted_at:     $(uptime -s 2>/dev/null)"
  echo
  echo "--- power mode (must match across A/B runs) ---"
  nvpmodel -q 2>/dev/null || echo "nvpmodel unavailable"
  echo
  echo "--- recent boot history (a POR shows as an unclean previous shutdown) ---"
  last -x reboot 2>/dev/null | head -10 || echo "last unavailable"
  echo
  echo "--- kernel boot list ---"
  journalctl --list-boots 2>/dev/null | tail -10 || echo "journalctl unavailable"
  echo
  echo "--- reset reason / power-on cause, if the SoC exposes it ---"
  for f in /sys/devices/soc0/soc_id /proc/device-tree/chosen/reset-reason; do
    [ -e "$f" ] && echo "$f: $(tr -d '\0' < "$f" 2>/dev/null)"
  done
} > "$DIR/boot.txt" 2>&1
cat "$DIR/boot.txt"

# ── tegrastats: CPU/GPU load, thermals, and VDD_IN (brownout evidence) ───────
# A reset preceded by a VDD_IN sag is a power problem, not a software crash.
if command -v tegrastats >/dev/null 2>&1; then
  tegrastats --interval 1000 --logfile "$DIR/tegrastats.txt" &
  TEGRA_PID=$!
  echo "tegrastats logging (pid $TEGRA_PID)"
else
  TEGRA_PID=""
  echo "WARNING: tegrastats not found — are you inside the container?"
fi

# ── Kernel events: USB drops, undervoltage, thermal, OOM ────────────────────
# dmesg is root-only when kernel.dmesg_restrict=1 (the default on this Jetson).
# Without this warning the capture just produces an empty file and you cannot
# tell "nothing happened" from "we were never allowed to look".
if [ "$(cat /proc/sys/kernel/dmesg_restrict 2>/dev/null)" = "1" ] && [ "$(id -u)" != "0" ]; then
  echo "WARNING: kernel.dmesg_restrict=1 and you are not root —"
  echo "         dmesg_events.txt WILL BE EMPTY regardless of what happens."
  echo "         Re-run with sudo to capture USB/power/thermal events."
fi
# -W (--follow-new) shows ONLY messages arriving from now on.  Plain -w dumps
# the entire existing ring buffer first, which makes the whole boot-time
# backlog look like it happened the instant the script started.
( dmesg -W 2>/dev/null \
    | grep -Ei 'usb|cdc_acm|ch341|ftdi|disconnect|undervoltage|brownout|thermal|throttl|oom|reset' \
    | while IFS= read -r l; do echo "$(date -Is) $l"; done \
    > "$DIR/dmesg_events.txt" ) &
DMESG_PID=$!

cleanup() {
  echo
  echo "stopping..."
  # tegrastats ignores SIGINT, so go straight to TERM and escalate.
  if [ -n "$TEGRA_PID" ]; then
    kill -TERM "$TEGRA_PID" 2>/dev/null
    sleep 0.5
    kill -9 "$TEGRA_PID" 2>/dev/null
  fi
  kill -9 "$DMESG_PID" 2>/dev/null
  {
    echo
    echo "session_end:  $(date -Is)"
    echo "boot_id:      $(cat /proc/sys/kernel/random/boot_id 2>/dev/null)"
    echo "uptime_s:     $(cut -d' ' -f1 /proc/uptime 2>/dev/null)"
  } >> "$DIR/boot.txt"

  echo
  echo "=== summary ==="
  START_ID=$(grep -m1 '^boot_id:' "$DIR/boot.txt" | awk '{print $2}')
  END_ID=$(tail -5 "$DIR/boot.txt" | grep -m1 '^boot_id:' | awk '{print $2}')
  if [ "$START_ID" != "$END_ID" ]; then
    echo "  !! JETSON REBOOTED DURING THE SESSION (boot_id changed)"
  else
    echo "  Jetson did NOT reboot (boot_id unchanged)"
  fi
  echo "  kernel events captured: $(wc -l < "$DIR/dmesg_events.txt" 2>/dev/null || echo 0)"
  if [ -s "$DIR/dmesg_events.txt" ]; then
    echo "  --- last few ---"
    tail -5 "$DIR/dmesg_events.txt" | sed 's/^/    /'
  fi
  echo
  echo "  files in $DIR"
  exit 0
}
trap cleanup INT TERM

echo "recording — Ctrl-C to stop and print the summary"
# NOTE: short sleeps on purpose.  bash does not run a trap until the currently
# executing command returns, so `sleep 3600` here made the script ignore SIGINT
# for up to an hour — kill -INT appeared to "not work" and only kill -9 helped.
while true; do sleep 1; done
